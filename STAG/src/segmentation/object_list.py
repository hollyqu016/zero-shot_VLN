# 复数还原时不能简单去尾's'的词(去掉后反而不成词)，直接跳过
_PLURAL_EXCEPTIONS = frozenset({"glass", "dress", "mattress", "grass", "class"})


def _singularize(word: str) -> str:
    """极简复数还原，只处理VLN指令里最常见的几种形态。"""
    if word in _PLURAL_EXCEPTIONS or len(word) <= 3:
        return word
    if word.endswith("ies"):
        return word[:-3] + "y"
    if word.endswith("ses") or word.endswith("xes") or word.endswith("hes"):
        return word[:-2]
    if word.endswith("s") and not word.endswith("ss"):
        return word[:-1]
    return word


