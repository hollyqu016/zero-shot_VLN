def resolve_area(name: str):
    """
    判断一个地标名是不是区域/房间。返回 (canonical_area_type, how)；
    不是区域则返回 (None, None)。

    先查别名表，再退化到"最后一个词"——"the master bedroom" / "a small kitchen"
    这类带修饰词的说法，中心语才是房间类型。
    """
    norm = normalize_category_name(name)
    if not norm:
        return None, None
    if norm in AREA_ALIASES:
        return AREA_ALIASES[norm], "exact"
    tokens = norm.split()

    # 具体房间类型优先于泛化的 room/area/space。
    #
    # "kitchen area" 按中心语规则取最后一个词 area -> 泛化 room -> 没有特征
    # 物体 -> 永远接不了地。实测这一条占了 area_no_proxy 的 155 次，仅次于
    # hallway。它说的明明是厨房，只是后面缀了个"区域"。
    # 先扫一遍所有 token/bigram，命中非泛化类型就直接用。
    for n in (2, 1):
        for i in range(len(tokens) - n + 1):
            t = AREA_ALIASES.get(" ".join(tokens[i:i + n]))
            if t and t not in GENERIC_AREA_TYPES:
                return t, "contains"

    if len(tokens) >= 2:
        tail2 = " ".join(tokens[-2:])
        if tail2 in AREA_ALIASES:
            return AREA_ALIASES[tail2], "head_noun"
    if tokens and tokens[-1] in AREA_ALIASES:
        return AREA_ALIASES[tokens[-1]], "head_noun"
    return None, None


def resolve_category(name: str):
    """
    把一个自由文本的地标名对齐到封闭词表里的类别。返回 (canonical_name, how)；
    对不上时返回 (None, 'unmatched')。

    匹配按可靠性从高到低依次尝试，命中即返回：
      1. exact      —— 归一化后精确等于某个类别
      2. synonym    —— 命中同义词表("couch" -> "sofa")
      3. singular   —— 复数还原后精确匹配("chairs" -> "chair")
      4. head_noun  —— 取短语最后一个词做中心语("dining table" -> "table",
                       "front door" -> "door")。VLN里绝大多数地标都是
                       "修饰词 + 中心语"的结构，这一条覆盖面最广。
      5. contains   —— 词表类别作为完整词出现在短语里("door mat"里的"mat"已被
                       同义词处理，这里兜底"the wooden kitchen door"这类长短语)

    返回的 how 字段会一路带到可视化里，方便判断某次grounding到底是靠哪条规则
    命中的——精确匹配和中心语匹配的可信度显然不一样。
    """
    norm = normalize_category_name(name)
    if not norm:
        return None, "unmatched"

    if norm in CATEGORY_NAMES_NORMALIZED:
        return NORMALIZED_TO_CANONICAL[norm], "exact"

    if norm in _SYNONYMS:
        return _SYNONYMS[norm], "synonym"

    tokens = norm.split()

    singular = " ".join(_singularize(t) for t in tokens)
    if singular in CATEGORY_NAMES_NORMALIZED:
        return NORMALIZED_TO_CANONICAL[singular], "singular"
    if singular in _SYNONYMS:
        return _SYNONYMS[singular], "synonym"

    if tokens:
        head = _singularize(tokens[-1])
        if head in CATEGORY_NAMES_NORMALIZED:
            return NORMALIZED_TO_CANONICAL[head], "head_noun"
        if head in _SYNONYMS:
            return _SYNONYMS[head], "synonym"

    token_set = set(_singularize(t) for t in tokens)
    for cat_norm, canonical in NORMALIZED_TO_CANONICAL.items():
        cat_tokens = cat_norm.split()
        if len(cat_tokens) == 1 and cat_tokens[0] in token_set:
            return canonical, "contains"

    return None, "unmatched"