# 每类房间的特征物体及权重。权重越高，看到它越能确定房间类型。
# 只列了确实存在于 CATEGORY_NAMES 里的类别（已核对）。
# hallway / room 刻意留空：走廊没有任何特征物体，只能靠几何形状判断，
